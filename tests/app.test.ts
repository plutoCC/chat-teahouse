  await t.test('actual SSE connection survives idle HTTP timeout, receives heartbeat and does not block shutdown', { timeout: 25_000 }, async () => {
    await app.listen({ host: '127.0.0.1', port });
    const abort = new AbortController();
    let reader: ReadableStreamDefaultReader<Uint8Array> | undefined;
    let deadline: ReturnType<typeof setTimeout> | undefined;
    try {
      const response = await fetch(`http://${host}/api/events`, { signal: abort.signal });
      assert.equal(response.status, 200);
      assert.match(response.headers.get('content-type') ?? '', /text\/event-stream/);
      assert.match(response.headers.get('content-security-policy') ?? '', /frame-ancestors 'none'/);
      assert.equal(response.headers.get('cache-control'), 'no-store');
      assert.equal(response.headers.get('cross-origin-resource-policy'), 'same-origin');
      reader = response.body!.getReader();
      const first = await reader.read();
      assert.equal(first.done, false);
      assert.match(new TextDecoder().decode(first.value), /event: change/);
      // Fastify's ordinary HTTP inactivity timeout is 10 seconds. The SSE
      // route must override it so the 15-second heartbeat is actually reached.
      const idleStarted = Date.now();
      const heartbeat = await reader.read();
      assert.equal(heartbeat.done, false, 'SSE ended before the idle heartbeat');
      assert.match(new TextDecoder().decode(heartbeat.value), /: heartbeat/);
      assert.ok(Date.now() - idleStarted >= 10_000, 'The stream must stay idle beyond the ordinary HTTP timeout');
      await Promise.race([
        close(),
        new Promise<never>((_, reject) => { deadline = setTimeout(() => reject(new Error('Open SSE connection blocked application shutdown')), 3000); }),
      ]);
      assert.equal((await reader.read()).done, true);
    } finally {
      clearTimeout(deadline);
      abort.abort();
      await reader?.cancel().catch(() => {});
      reader?.releaseLock();
      // Also release sockets on failure so cleanup cannot hang on the regression.
      app.server.closeAllConnections();
    }
  });
