import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:net';
import { mkdirSync,mkdtempSync,rmSync,lstatSync,realpathSync } from 'node:fs';
import { resolve,join,dirname,basename } from 'node:path';
import { chromium } from 'playwright-core';
import { buildApp } from '../../server/app.js';
import { fixtureModelCatalog } from './model-list-fixture.js';

test('production UI can configure browser members, show status, accept a live human message and display an automatic reply',async t=>{
  const tempRoot=resolve('.test-artifacts');mkdirSync(tempRoot,{recursive:true});const dataDir=mkdtempSync(join(tempRoot,'browser-ui-'));
  const port=await new Promise<number>((resolve,reject)=>{const s=createServer();s.once('error',reject);s.listen(0,'127.0.0.1',()=>{const p=(s.address() as {port:number}).port;s.close(()=>resolve(p));});});
  let finish!:()=>void;
  const runtime=await buildApp({dataDir,port,production:true,modelCatalogFetcher:fixtureModelCatalog,browserDriver:{generate:async r=>{
    r.prepare();r.progress({phase:'reading',message:'本地功能测试：模拟网页生成中，不会请求真实模型。',sent:true});
    await new Promise<void>((resolve,reject)=>{finish=resolve;r.signal.addEventListener('abort',()=>reject(new Error('cancelled')),{once:true});});
    return {content:'【本地功能测试，非真实模型回答】浏览器连接结果已写回群聊；后续成员可以读取这条公开观点。',reasoning:''};
  }}});
  await runtime.app.listen({host:'127.0.0.1',port});
  const browser=await chromium.launch({channel:process.env.CHAT_TEA_BROWSER_CHANNEL??'msedge',headless:true,chromiumSandbox:true});
  t.after(async()=>{await browser.close();await runtime.app.close();assert.equal(lstatSync(dataDir).isSymbolicLink(),false);const target=realpathSync(dataDir);assert.equal(dirname(target),realpathSync(tempRoot));assert.ok(basename(target).startsWith('browser-ui-'));rmSync(target,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:{width:1365,height:900}});const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${port}/`);
  await page.getByRole('button',{name:'浏览器连接',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'DeepSeek',exact:true}).click();
  await page.getByRole('button',{name:'打开 / 显示专用窗口',exact:true}).waitFor();
  assert.match(await page.getByRole('dialog').innerText(),/高级页面适配/);
  mkdirSync(resolve('docs'),{recursive:true});await page.screenshot({path:resolve('docs/browser-connector-settings.png')});
  await page.getByRole('button',{name:'关闭对话框',exact:true}).click();
  await page.getByRole('button',{name:'新建群聊',exact:true}).click();
  await page.getByRole('textbox',{name:'圆桌名称',exact:true}).fill('自动连接验收 · 本地模拟');
  await page.getByRole('textbox',{name:/^讨论目标/}).fill('只测试自动接力流程，不调用真实模型。');
  for(const name of ['演示成员 A','演示成员 B','演示成员 C'])await page.getByRole('checkbox',{name:`邀请 ${name}`,exact:true}).check();
  await page.getByRole('button',{name:'创建圆桌',exact:true}).click();
  await page.getByRole('heading',{name:'自动连接验收 · 本地模拟',exact:true}).waitFor();
  await page.getByRole('button',{name:'成员与设置',exact:true}).click();
  await page.getByRole('button',{name:'编辑 演示成员 A',exact:true}).click();
  await page.getByRole('combobox',{name:'连接方式',exact:true}).selectOption('browser');
  await page.getByRole('combobox',{name:'模型供应商',exact:true}).selectOption('qwen');
  await page.getByRole('textbox',{name:'显示名称',exact:true}).fill('Qwen 连接器（本地模拟）');
  await page.getByRole('button',{name:'保存成员',exact:true}).click();
  await page.getByRole('button',{name:'请 Qwen 连接器（本地模拟） 发言',exact:true}).click();
  await page.getByRole('button',{name:'关闭设置',exact:true}).click();
  await page.waitForFunction(()=>{
    const panel=document.querySelector('.details-panel');
    return panel?.hasAttribute('inert')&&panel.getBoundingClientRect().left>=innerWidth;
  });
  await page.getByText('本地功能测试：模拟网页生成中，不会请求真实模型。',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'提交回复并继续',exact:true}).count(),0);
  await page.getByRole('textbox',{name:'输入讨论问题',exact:true}).fill('【插话测试】我的观点也可以被质疑。');
  await page.getByRole('button',{name:'加入讨论',exact:true}).click();
  await page.getByText('【插话测试】我的观点也可以被质疑。',{exact:true}).waitFor();
  finish();await page.getByText('【本地功能测试，非真实模型回答】浏览器连接结果已写回群聊；后续成员可以读取这条公开观点。',{exact:true}).waitFor();
  await page.getByRole('button',{name:'开始讨论',exact:true}).waitFor();
  assert.equal(await page.getByText('浏览器读取',{exact:true}).count(),1);
  await page.screenshot({path:resolve('docs/browser-connector-chat.png')});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
});
