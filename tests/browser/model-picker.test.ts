import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, rmSync, realpathSync, lstatSync } from 'node:fs';
import { resolve, join, dirname, basename } from 'node:path';
import { createServer } from 'node:net';
import { chromium } from 'playwright-core';
import { buildApp } from '../../server/app.js';
import { fixtureModelCatalog } from './model-list-fixture.js';

test('official model selectors preserve saved values, filter, refresh, save and work for members on mobile', {timeout:60000}, async t => {
  const root=resolve('.test-artifacts');mkdirSync(root,{recursive:true});const dataDir=mkdtempSync(join(root,'model-picker-ui-'));
  const port=await new Promise<number>((done,reject)=>{const s=createServer();s.once('error',reject);s.listen(0,'127.0.0.1',()=>{const n=(s.address() as {port:number}).port;s.close(()=>done(n));});});
  const runtime=await buildApp({dataDir,port,production:true,modelCatalogFetcher:fixtureModelCatalog});
  const host=`127.0.0.1:${port}`,url=`http://${host}`;
  const boot=(await runtime.app.inject({url:'/api/bootstrap',headers:{host}})).json();
  const headers={host,origin:url,'x-csrf-token':boot.csrfToken};
  await runtime.app.inject({method:'PUT',url:'/api/providers/openai',headers,payload:{model:'gpt-existing-private',apiKey:'fixture-only-never-sent'}});
  await runtime.app.listen({host:'127.0.0.1',port});
  const browser=await chromium.launch({channel:process.env.CHAT_TEA_BROWSER_CHANNEL??'msedge',headless:true,chromiumSandbox:true});
  t.after(async()=>{await browser.close();await runtime.app.close();assert.equal(lstatSync(dataDir).isSymbolicLink(),false);const target=realpathSync(dataDir);assert.equal(dirname(target),realpathSync(root));assert.ok(basename(target).startsWith('model-picker-ui-'));rmSync(target,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:{width:1365,height:980}});page.setDefaultTimeout(10000);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>route.request().url().startsWith(url)?route.continue():route.abort());
  const reads:unknown[]=[],writes:unknown[]=[];
  page.on('request',r=>{if(r.url().endsWith('/api/providers/openai/models'))reads.push(r.postDataJSON());if(r.method()==='PUT'&&r.url().endsWith('/api/providers/openai'))writes.push(r.postDataJSON());});
  await page.goto(url);await page.getByRole('button',{name:'模型连接',exact:true}).click();
  const select=page.getByRole('combobox',{name:'默认模型',exact:true});
  await page.getByText('本地测试模型列表，未访问外部供应商。',{exact:false}).waitFor();
  assert.equal(await select.inputValue(),'gpt-existing-private');
  assert.match(await select.locator('option:checked').innerText(),/尚未在本次列表中确认/);
  assert.equal(await page.getByRole('textbox',{name:'自定义模型 ID',exact:true}).count(),0);
  await page.getByRole('searchbox',{name:'筛选模型选项',exact:true}).fill('6.1-sol');
  assert.equal(await select.locator('option').count(),2);await select.selectOption('gpt-6.1-sol');
  await page.getByRole('searchbox',{name:'筛选模型选项',exact:true}).fill('');
  await page.getByRole('textbox',{name:/API Key/}).fill('unsaved-do-not-send');
  await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/providers/openai/models')&&r.status()===200),page.getByRole('button',{name:'刷新列表',exact:true}).click()]);
  assert.ok(reads.length>=2);assert.equal(writes.length,0);assert.doesNotMatch(JSON.stringify(reads),/unsaved-do-not-send/);
  await page.getByRole('textbox',{name:/API Key/}).fill('');
  await page.getByRole('button',{name:'保存连接',exact:true}).click();await page.getByText('连接配置已保存',{exact:true}).waitFor();
  assert.equal(runtime.store.providers().find(p=>p.id==='openai')!.model,'gpt-6.1-sol');
  assert.equal(runtime.vault.get('openai'),'fixture-only-never-sent');
  assert.deepEqual(runtime.store.groups()[0].participants,boot.groups[0].participants);
  await page.getByRole('heading',{name:'模型连接',exact:true}).scrollIntoViewIfNeeded();
  mkdirSync(resolve('output/playwright'),{recursive:true});await page.screenshot({path:resolve('output/playwright/model-picker-desktop.png')});
  await page.getByRole('button',{name:'关闭对话框',exact:true}).click();
  await page.getByRole('button',{name:'成员与设置',exact:true}).click();
  await page.getByRole('button',{name:'编辑 演示成员 A',exact:true}).click();
  await page.getByRole('combobox',{name:'模型供应商',exact:true}).selectOption('openai');
  const memberSelect=page.getByRole('combobox',{name:'模型名称',exact:true});await memberSelect.selectOption('gpt-6-astra');
  await page.getByRole('combobox',{name:'模型供应商',exact:true}).selectOption('qwen');
  await page.getByRole('combobox',{name:'模型供应商',exact:true}).selectOption('openai');assert.equal(await memberSelect.inputValue(),'gpt-6-astra');
  await page.getByRole('button',{name:'保存成员',exact:true}).click();await page.getByRole('dialog').waitFor({state:'hidden'});
  assert.equal(runtime.store.groups()[0].participants[0].model,'gpt-6-astra');
  await page.getByRole('button',{name:'编辑 演示成员 A',exact:true}).click();assert.equal(await memberSelect.inputValue(),'gpt-6-astra');
  await page.setViewportSize({width:390,height:844});await memberSelect.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  const box=await memberSelect.boundingBox();assert.ok(box&&box.x>=0&&box.x+box.width<=390);
  await page.screenshot({path:resolve('output/playwright/model-picker-mobile.png')});assert.deepEqual(errors,[]);
});
